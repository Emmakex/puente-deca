import {
  createHash
} from "node:crypto";
import {
  readFile
} from "node:fs/promises";
import {
  resolve
} from "node:path";
import {
  canonicalJson
} from "../../packages/core/src/canonical-json.mjs";
import {
  serializeEcmrD25aEnvelope
} from "../../packages/ecmr-xml/src/d25a-serializer.mjs";
import {
  readEcmrD25aSchemaManifest
} from "../../packages/ecmr-xml/src/schema-bundle.mjs";

const requireText = (
  value,
  name
) => {
  if (
    typeof value !== "string" ||
    value.trim().length === 0
  ) {
    const error =
      new Error(
        `${name} is required`
      );
    error.code =
      "ECMR_D25A_EVIDENCE_CONFIGURATION_INVALID";
    throw error;
  }

  return value.trim();
};

const sha256 = (
  value
) =>
  `sha256:${createHash("sha256")
    .update(value)
    .digest("hex")}`;

const fail = (
  code,
  message
) => {
  const error =
    new Error(
      message
    );
  error.code =
    code;
  throw error;
};

const evidencePath =
  resolve(
    requireText(
      process.env
        .ECMR_D25A_EVIDENCE,
      "ECMR_D25A_EVIDENCE"
    )
  );

const projectionPath =
  resolve(
    requireText(
      process.env
        .ECMR_D25A_PROJECTION,
      "ECMR_D25A_PROJECTION"
    )
  );

const schemaDirectory =
  resolve(
    process.env
      .ECMR_D25A_SCHEMA_DIR ??
      "vendor/uncefact/ecmr/D25A"
  );

try {
  const evidence =
    JSON.parse(
      await readFile(
        evidencePath,
        "utf8"
      )
    );
  const projection =
    JSON.parse(
      await readFile(
        projectionPath,
        "utf8"
      )
    );

  const {
    evidenceSha256,
    ...coreEvidence
  } = evidence;

  const calculatedEvidenceHash =
    sha256(
      Buffer.from(
        canonicalJson(
          coreEvidence
        ),
        "utf8"
      )
    );

  if (
    evidenceSha256 !==
      calculatedEvidenceHash
  ) {
    fail(
      "ECMR_D25A_EVIDENCE_HASH_MISMATCH",
      "eCMR D25A acceptance evidence hash does not match its canonical content"
    );
  }

  if (
    evidence.status !==
      "pass" ||
    evidence.check !==
      "ecmr-d25a-generated-xml-acceptance" ||
    evidence.validation
      ?.schemaConformance !==
      "official-d25a-xsd-pass" ||
    evidence.validation
      ?.networkAccess !==
      false
  ) {
    fail(
      "ECMR_D25A_EVIDENCE_STATUS_INVALID",
      "eCMR D25A acceptance evidence does not represent an offline official-XSD PASS"
    );
  }

  const projectionSha256 =
    sha256(
      Buffer.from(
        canonicalJson(
          projection
        ),
        "utf8"
      )
    );

  if (
    evidence
      .projectionSha256 !==
    projectionSha256
  ) {
    fail(
      "ECMR_D25A_EVIDENCE_PROJECTION_MISMATCH",
      "eCMR D25A evidence does not match the supplied structured projection"
    );
  }

  const wire =
    serializeEcmrD25aEnvelope(
      projection
    );
  const xmlSha256 =
    sha256(
      Buffer.from(
        wire.xml,
        "utf8"
      )
    );

  if (
    evidence.validation
      ?.xmlSha256 !==
    xmlSha256
  ) {
    fail(
      "ECMR_D25A_EVIDENCE_XML_MISMATCH",
      "eCMR D25A evidence does not match XML regenerated by the pinned serializer"
    );
  }

  const installed =
    await readEcmrD25aSchemaManifest(
      schemaDirectory
    );
  const manifest =
    installed.manifest;

  for (
    const field of
    [
      "archiveSha256",
      "nestedSchemaArchiveSha256",
      "rootSchemaSha256",
      "schemaTreeSha256",
      "schemaFileCount"
    ]
  ) {
    if (
      evidence.validation
        ?.[field] !==
      manifest[field]
    ) {
      fail(
        "ECMR_D25A_EVIDENCE_SCHEMA_MISMATCH",
        `eCMR D25A evidence does not match installed schema evidence: ${field}`
      );
    }
  }

  if (
    evidence.validation
      ?.release !==
        manifest.release ||
    evidence.validation
      ?.sourceFile !==
        manifest.sourceFile ||
    evidence.validation
      ?.sourceFileId !==
        manifest.sourceFileId ||
    evidence.validation
      ?.rootSchema !==
        manifest.rootSchema ||
    evidence.validation
      ?.nestedSchemaArchive !==
        manifest.nestedSchemaArchive
  ) {
    fail(
      "ECMR_D25A_EVIDENCE_PROFILE_MISMATCH",
      "eCMR D25A evidence does not match the installed pinned D25A profile"
    );
  }

  process.stdout.write(
    `${JSON.stringify(
      {
        status: "ok",
        check:
          "ecmr-d25a-acceptance-evidence-verify",
        evidenceSha256,
        projectionSha256,
        xmlSha256,
        schemaTreeSha256:
          manifest
            .schemaTreeSha256,
        schemaConformance:
          evidence
            .validation
            .schemaConformance
      },
      null,
      2
    )}\n`
  );
} catch (error) {
  process.stderr.write(
    `${JSON.stringify({
      status: "error",
      check:
        "ecmr-d25a-acceptance-evidence-verify",
      code:
        typeof error?.code ===
          "string"
          ? error.code
          : "ECMR_D25A_EVIDENCE_VERIFY_FAILED"
    })}\n`
  );

  process.exitCode = 1;
}
